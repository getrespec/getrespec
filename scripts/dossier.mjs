export class Refusal extends Error {}
const refuse = (msg) => {
  throw new Refusal(msg);
};

// Locale-free grouping so the output is byte-identical on every machine.
const num = (n, s) => String(n).replace(/\B(?=(\d{3})+(?!\d))/g, s);
const esc = (v) =>
  String(v).replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]);
const isText = (v) => typeof v === "string" && v.trim() !== "";

function readJson(path, label) {
  let text;
  try {
    text = readFileSync(path, "utf8");
  } catch {
    refuse(`${label}: not found`);
  }
  try {
    return JSON.parse(text);
  } catch {
    refuse(`${label}: not valid JSON`);
  }
}

function validate(d, id) {
  if (!d || typeof d !== "object" || Array.isArray(d)) refuse("dossier: must be a JSON object");
  if (d.schema_version === 1) refuse("schema_version: 1 has no plain section; add plain (flows/dossier.md) and set schema_version to 2");
  if (d.schema_version !== 2) refuse(`schema_version: expected 2, got ${JSON.stringify(d.schema_version)}`);
  if (d.module !== id) refuse(`module: expected "${id}"`);
  const p = d.plain;
  if (!p || typeof p !== "object" || Array.isArray(p)) refuse("plain: expected an object");
  if (!isText(p.built)) refuse("plain.built: required text");
  if (p.missing !== undefined && !isText(p.missing)) refuse("plain.missing: text or leave it out");
  const items = (key, min, max, fields) => {
    const v = p[key] ?? (min ? undefined : []);
    if (!Array.isArray(v) || v.length < min || v.length > max) refuse(`plain.${key}: expected ${min} to ${max} entries`);
    v.forEach((x, i) => fields.forEach((k) => isText(x?.[k]) || refuse(`plain.${key}[${i}].${k}: required text`)));
  };
  items("skills", 2, 5, ["title", "detail"]);
  items("questions", 2, 3, ["question", "good_answer"]);
  items("terms", 0, 8, ["term", "meaning"]);
  if (!isText(d.summary)) refuse("summary: required text");
  if (!Array.isArray(d.decisions) || d.decisions.length < 3 || d.decisions.length > 5)
    refuse("decisions: expected 3 to 5 entries");
  d.decisions.forEach((x, i) => {
    for (const k of ["title", "why", "alternatives", "tradeoff"])
      if (!isText(x?.[k])) refuse(`decisions[${i}].${k}: required text`);
    const r = x.ref;
    if (!r || !isText(r.file) || !Number.isInteger(r.from) || !Number.isInteger(r.to))
      refuse(`decisions[${i}].ref: expected { file, from, to }`);
  });
  if (!Array.isArray(d.questions) || d.questions.length < 1 || d.questions.length > 10)
    refuse("questions: expected 1 to 10 entries");
  d.questions.forEach((q, i) => isText(q) || refuse(`questions[${i}]: required text`));
}

function excerpt(moduleDir, ref, label) {
  const [first, ...rest] = ref.file.split("/");
  if (first !== "work" || !rest.length) refuse(`${label}.file: must start with work/`);
  const found = safeInside(join(moduleDir, "work"), rest.join("/"));
  if (found.error === "missing") refuse(`${label}.file: not found`);
  if (found.error) refuse(`${label}.file: must stay inside work/`);
  const st = statSync(found.path);
  if (!st.isFile()) refuse(`${label}.file: not a file`);
  if (st.size > MAX_TEXT) refuse(`${label}.file: larger than 512 KB`);
  const buf = readFileSync(found.path);
  if (buf.subarray(0, 8000).includes(0)) refuse(`${label}.file: binary file`);
  const lines = buf.toString("utf8").replace(/\r?\n$/, "").split(/\r?\n/);
  if (ref.from < 1 || ref.to < ref.from || ref.to > lines.length)
    refuse(`${label}: lines ${ref.from}-${ref.to} are outside 1-${lines.length}`);
  if (ref.to - ref.from + 1 > MAX_EXCERPT_LINES)
    refuse(`${label}: excerpt is longer than ${MAX_EXCERPT_LINES} lines; cite a shorter range`);
  return lines.slice(ref.from - 1, ref.to).join("\n");
}

// Every string that ends up in the HTML, labelled by where it came from.
function keyCheck(entries) {
  for (const [label, value] of entries) {
    if (typeof value !== "string") continue;
    for (const [name, re] of KEY_PATTERNS) if (re.test(value)) refuse(`${label}: looks like a ${name}; remove it and render again`);
  }
}

export function buildDossier({ learnerDir, id, footer = true }) {
  const state = readJson(join(learnerDir, "state.json"), "state.json");
  const mod = (state?.curriculum?.modules ?? []).find((m) => m?.id === id);
  if (typeof id !== "string" || !/^[A-Za-z0-9_-]+$/.test(id) || !mod) refuse(`module id: "${id}" is not in state.json curriculum.modules`);
  const lang = state.learner?.language === "tr" ? "tr" : "en";
  const t = TEXT[lang];
  const moduleDir = join(learnerDir, "modules", id);

  const d = readJson(join(learnerDir, "dossier", `${id}.json`), `dossier/${id}.json`);
  validate(d, id);

  const evaluation = readJson(join(moduleDir, "evaluation.json"), `modules/${id}/evaluation.json`);
  const attempts = Array.isArray(evaluation?.attempts) ? evaluation.attempts : [];
  const at = attempts.findLastIndex((a) => a?.passed === true);
  if (at < 0) refuse(`modules/${id}/evaluation.json: no passed attempt yet; finish the assignment with /respec submit first`);
  const a = attempts[at];
  const ev = `evaluation.attempts[${at}]`;
  if (typeof a.total !== "number" || !Array.isArray(a.rubric)) refuse(`${ev}: expected total and rubric[]`);
  const rubric = a.rubric.filter((r) => r && typeof r === "object");
  const list = (v) => (Array.isArray(v) ? v.filter(isText) : []);
  const strengths = list(a.strengths);
  const gaps = list(a.gaps);
  const defense = (Array.isArray(a.defense) ? a.defense : []).filter((q) => isText(q?.question) && isText(q?.answer));
  const usage = a.usage && typeof a.usage === "object" ? t.usageLine(a.usage).filter(Boolean) : [];

  const codes = d.decisions.map((x, i) => excerpt(moduleDir, x.ref, `decisions[${i}].ref`));

  keyCheck([
    ["state.json module title", mod.title],
    ["state.json target_role.title", state.target_role?.title],
    ["plain.built", d.plain.built],
    ["plain.missing", d.plain.missing],
    ...d.plain.skills.flatMap((x, i) => ["title", "detail"].map((k) => [`plain.skills[${i}].${k}`, x[k]])),
    ...d.plain.questions.flatMap((x, i) => ["question", "good_answer"].map((k) => [`plain.questions[${i}].${k}`, x[k]])),
    ...(d.plain.terms ?? []).flatMap((x, i) => ["term", "meaning"].map((k) => [`plain.terms[${i}].${k}`, x[k]])),
    ["summary", d.summary],
    ...d.decisions.flatMap((x, i) => [
      ...["title", "why", "alternatives", "tradeoff", "ref"].map((k) => [`decisions[${i}].${k}`, k === "ref" ? x.ref.file : x[k]]),
      [`decisions[${i}].ref (code in ${x.ref.file})`, codes[i]],
    ]),
    ...d.questions.map((q, i) => [`questions[${i}]`, q]),
    ...rubric.flatMap((r, i) => [[`${ev}.rubric[${i}].item`, r.item], [`${ev}.rubric[${i}].comment`, r.comment]]),
    ...strengths.map((s, i) => [`${ev}.strengths[${i}]`, s]),
    ...gaps.map((s, i) => [`${ev}.gaps[${i}]`, s]),
    ...defense.flatMap((q, i) => [[`${ev}.defense[${i}].question`, q.question], [`${ev}.defense[${i}].answer`, q.answer]]),
    [`${ev}.date`, a.date],
  ]);

  const title = isText(mod.title) ? mod.title : id;
  const section = (key, heading, body) =>
    `<section aria-labelledby="h-${key}">\n<h2 id="h-${key}">${esc(heading)}</h2>\n${body}\n</section>`;
  const ul = (items) => `<ul>\n${items.map((s) => `<li>${esc(s)}</li>`).join("\n")}\n</ul>`;

  const parts = [];
  if (mod.status === "assisted") parts.push(`<p class="banner" role="note"><strong>${esc(t.assisted)}</strong></p>`);
  // First page: for a recruiter or anyone who doesn't read code. The technical part follows unchanged.
  const pl = d.plain;
  parts.push(
    `<section class="summary" aria-labelledby="h-plain">\n<h2 id="h-plain">${esc(t.plain)}</h2>\n` +
      `<p><strong>${esc(t.built)}:</strong> ${esc(pl.built)}</p>\n<h3>${esc(t.skills)}</h3>\n<ul>\n` +
      pl.skills.map((x) => `<li><strong>${esc(x.title)}</strong> ${esc(x.detail)}</li>`).join("\n") +
      `\n</ul>\n<p><strong>${esc(t.result)}:</strong> ${esc(a.total)}/100, ${esc(t.passed)}</p>\n` +
      (isText(pl.missing) ? `<p><strong>${esc(t.missing)}:</strong> ${esc(pl.missing)}</p>\n` : "") +
      `<p class="note">${esc(t.limits)}</p>\n</section>`,
  );
  parts.push(
    section(
      "ask",
      t.ask,
      `<p>${esc(t.askLead)}</p>\n<ol class="ask">\n` +
        pl.questions.map((x) => `<li><strong>${esc(x.question)}</strong><br>${esc(t.good)}: ${esc(x.good_answer)}</li>`).join("\n") +
        "\n</ol>",
    ),
  );
  if (pl.terms?.length)
    parts.push(section("terms", t.terms, `<dl>\n${pl.terms.map((x) => `<dt>${esc(x.term)}</dt><dd>${esc(x.meaning)}</dd>`).join("\n")}\n</dl>`));
  parts.push(`<p class="part" role="note">${esc(t.part)}</p>`);
  parts.push(
    `<section class="summary" aria-labelledby="h-summary">\n<h2 id="h-summary">${esc(t.summary)}</h2>\n<p>${esc(d.summary)}</p>\n` +
      `<p><strong>${esc(t.result)}:</strong> ${esc(a.total)}/100, ${esc(t.passed)}</p>\n` +
      `<p><strong>${esc(t.best)}:</strong> ${esc(d.questions[0])}</p>\n</section>`,
  );
  parts.push(
    section(
      "decisions",
      t.decisions,
      d.decisions
        .map(
          (x, i) =>
            `<article>\n<h3>${esc(x.title)}</h3>\n<dl>\n` +
            [["why", t.why], ["alternatives", t.alternatives], ["tradeoff", t.tradeoff]]
              .map(([k, label]) => `<dt>${esc(label)}</dt><dd>${esc(x[k])}</dd>`)
              .join("\n") +
            `\n</dl>\n<p class="note">${esc(t.codeRef(i + 1, x.ref.file, x.ref.from, x.ref.to))}</p>\n</article>`,
        )
        .join("\n"),
    ),
  );
  parts.push(section("questions", t.questions, `<ol>\n${d.questions.map((q) => `<li>${esc(q)}</li>`).join("\n")}\n</ol>`));
  if (defense.length)
    parts.push(
      section("defense", t.defense, `<dl>\n${defense.map((q) => `<dt>${esc(q.question)}</dt><dd>${esc(q.answer)}</dd>`).join("\n")}\n</dl>`),
    );
  let evalBody =
    `<p><strong>${esc(t.result)}:</strong> ${esc(a.total)}/100, ${esc(t.passed)}</p>\n` +
    (rubric.length
      ? `<table>\n<thead><tr><th scope="col">${esc(t.item)}</th><th scope="col">${esc(t.score)}</th><th scope="col">${esc(t.comment)}</th></tr></thead>\n<tbody>\n` +
        rubric
          .map((r) => `<tr><td>${esc(r.item ?? "")}</td><td class="num">${esc(r.score ?? "")}/${esc(r.weight ?? "")}</td><td>${esc(r.comment ?? "")}</td></tr>`)
          .join("\n") +
        `\n</tbody>\n</table>`
      : "");
  if (strengths.length) evalBody += `\n<h3>${esc(t.strengths)}</h3>\n${ul(strengths)}`;
  if (gaps.length) evalBody += `\n<h3>${esc(t.gaps)}</h3>\n${ul(gaps)}`;
  parts.push(section("evaluation", t.evaluation, evalBody));
  if (usage.length) parts.push(section("usage", t.usage, `<p>${esc(usage.join(", "))}</p>`));
  parts.push(
    section(
      "code",
      t.code,
      d.decisions
        .map(
          (x, i) =>
            `<figure>\n<figcaption><strong>${i + 1}. ${esc(x.title)}</strong><br>${esc(t.lines(x.ref.file, x.ref.from, x.ref.to))}</figcaption>\n` +
            `<pre><code>${esc(codes[i])}</code></pre>\n</figure>`,
        )
        .join("\n") + (isText(a.date) ? `\n<p class="note">${esc(t.graded(a.date))}</p>` : ""),
    ),
  );

  const foot = `<p>${esc(t.limits)}</p>` + (footer ? `\n<p><a href="${t.link}">${esc(t.made)}</a></p>` : "");
  const role = isText(state.target_role?.title) ? `\n<p class="sub">${esc(state.target_role.title)}</p>` : "";

  return `<!doctype html>
<html lang="${lang}">
<head>
<meta charset="utf-8">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'unsafe-inline'; img-src data:">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="generator" content="Respec dossier, schema 2">
<title>${esc(`${t.kind}: ${title}`)}</title>
<style>${CSS}</style>
</head>
<body>
<main>
<header>
<p class="eyebrow">${esc(t.kind)} · ${esc(id)}</p>
<h1>${esc(title)}</h1>${role}
</header>
${parts.join("\n")}
</main>
<footer>
${foot}
</footer>
</body>
</html>
`;
}

